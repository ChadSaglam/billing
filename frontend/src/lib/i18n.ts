/** Exposed for tests (fallback checks); treat as read-only in app code. */
export const dictionaries: Record<Locale, Partial<Record<TKey, string>>> = { de, en };

export type TParams = Record<string, string | number>;

function interpolate(template: string, params?: TParams): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}

// ── locale store ──────────────────────────────────────────────────────

function isLocale(value: unknown): value is Locale {
  return value === 'de' || value === 'en';
}

function readStored(): Locale | null {
  try {
    const stored = globalThis.localStorage?.getItem(STORAGE_KEY);
    return isLocale(stored) ? stored : null;
  } catch {
    return null;
  }
}

function writeStored(locale: Locale) {
  try {
    globalThis.localStorage?.setItem(STORAGE_KEY, locale);
  } catch {
    // Private mode / blocked storage: the choice just does not persist.
  }
}

function applyLang(locale: Locale) {
  if (typeof document !== 'undefined') document.documentElement.lang = locale;
}

let currentLocale: Locale = readStored() ?? DEFAULT_LOCALE;
applyLang(currentLocale);

const listeners = new Set<() => void>();

export function getLocale(): Locale {
  return currentLocale;
}

export function setLocale(locale: Locale) {
  if (!isLocale(locale)) return;
  currentLocale = locale;
  writeStored(locale);
  applyLang(locale);
  listeners.forEach((fn) => fn());
}

export function subscribe(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/** Test hook: re-read localStorage (or fall back to DE) and notify. */
export function resetLocale() {
  currentLocale = readStored() ?? DEFAULT_LOCALE;
  applyLang(currentLocale);
  listeners.forEach((fn) => fn());
}

// ── translate ─────────────────────────────────────────────────────────

/**
 * Translate `key` in the given (default: current) locale. Falls back to
 * DE, then to the key itself so a missing entry is visible, never blank.
 */
export function t(key: TKey, params?: TParams, locale: Locale = currentLocale): string {
  const text = dictionaries[locale]?.[key] ?? de[key] ?? key;
  return interpolate(text, params);
}

/** Keys defined in DE but missing in `locale` — used by tests to keep EN complete. */
export function missingKeys(locale: Locale): TKey[] {
  const dict = dictionaries[locale];
  return (Object.keys(de) as TKey[]).filter((key) => !(key in dict));
}

/** Document-status label (`status.<value>`), unknown statuses pass through. */
export function statusLabel(status: string, locale: Locale = currentLocale): string {
  const key = `status.${status}` as TKey;
  return key in de ? t(key, undefined, locale) : status;
}

// ── React ─────────────────────────────────────────────────────────────

export function useLocale(): Locale {
  return useSyncExternalStore(subscribe, getLocale, () => DEFAULT_LOCALE);
}

/**
 * `const { t, locale, setLocale } = useT();` — re-renders on locale change.
 */
export function useT() {
  const locale = useLocale();
  const translate = useCallback(
    (key: TKey, params?: TParams) => t(key, params, locale),
    [locale],
  );
  return { t: translate, locale, setLocale };
}
